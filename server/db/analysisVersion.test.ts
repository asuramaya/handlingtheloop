import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { THIRD_PARTY_ANALYSIS_VERSION } from "./analysis";
import { sourceFiles, stripComments } from "../../src/htl/testing/sourceScan";

// THE DON'T-DOWNGRADE GUARD IS `excluded.version >= track_analysis.version`, SO A TIE OVERWRITES.
// `version` is an OPTIONAL parameter of upsertAnalysis, so omitting it is silent, legal, and lands
// on the schema default — which ties with every row that also took the default. That omission is
// what the /api/features lane shipped with, and what it cost is measured in the constant's comment.
//
// So the assertion worth having is not about the number. It is that NO CALLER OMITS IT: the next
// contributor lane gets the same tie for the same reason, and nothing in the type system says so.

const root = fileURLToPath(new URL("../..", import.meta.url));

describe("analysis contribution versions", () => {
  test("the third-party lane sits BELOW the schema default, read from the migration not from memory", () => {
    const sql = readFileSync(`${root}migrations/0004_analysis.sql`, "utf8");
    const m = sql.match(/version\s+INTEGER\s+NOT NULL\s+DEFAULT\s+(\d+)/i);
    expect(m, "migration 0004 no longer declares a default for track_analysis.version").not.toBeNull();
    const schemaDefault = Number(m![1]);
    // Strictly below: at the default it TIES, and `>=` makes a tie an overwrite.
    expect(THIRD_PARTY_ANALYSIS_VERSION).toBeLessThan(schemaDefault);
  });

  test("every upsertAnalysis call site names a version — an omitted one silently ties", () => {
    const offenders: string[] = [];
    for (const f of [...sourceFiles(`${root}worker`), ...sourceFiles(`${root}server`), ...sourceFiles(`${root}src`)]) {
      const src = stripComments(f.src);
      // Each call's argument text, up to the matching close of the object literal it is given.
      // `function upsertAnalysis(` is the DECLARATION, whose parameter object also has no
      // `version:` key at the top level — the scan found it on the first run, which is the
      // population check doing its job rather than a nuisance.
      for (const m of src.matchAll(/(?<!function\s)\bupsertAnalysis\s*\(/g)) {
        const open = src.indexOf("{", m.index! + m[0].length);
        if (open < 0) continue;
        let depth = 0;
        let end = open;
        for (; end < src.length; end++) {
          if (src[end] === "{") depth++;
          else if (src[end] === "}" && --depth === 0) break;
        }
        const args = src.slice(open, end + 1);
        if (!/\bversion\s*:/.test(args)) offenders.push(`${f.path} — upsertAnalysis({...}) with no \`version:\``);
      }
    }
    expect(offenders, offenders.join("\n")).toEqual([]);
  });
});

describe("the published dataset carries provenance", () => {
  // ★ THE EXPORT ASSERTS AN ORIGIN IT CANNOT SUPPORT FOR EVERY ROW. It publishes this table as
  // "derived features … generated by Handling The Loop", which is true of a row our detector
  // produced from decoded audio and false of one /api/features copied out of MusicBrainz →
  // AcousticBrainz. `version` is the only thing that tells them apart, and it only became able to
  // tell them apart when the third-party lane stopped defaulting to 1 (above).
  //
  // Pinned at both ends, because either one silently re-mixes them: the query must SELECT it and the
  // exported row must CARRY it. Dropping it from the JSONL would leave the column selected and the
  // dataset just as undifferentiated — the sort of half-fix that reads as done.
  const root = fileURLToPath(new URL("../..", import.meta.url));

  test("listAnalysis selects `version` — the export's only provenance", () => {
    const sql = readFileSync(`${root}server/db/analysis.ts`, "utf8");
    const q = sql.match(/SELECT ([^"]*?) FROM track_analysis ORDER BY/);
    expect(q, "listAnalysis's paged query no longer looks the way this test reads it").not.toBeNull();
    expect(q![1]).toMatch(/\bversion\b/);
  });

  test("the exported row carries `version`", () => {
    const admin = readFileSync(`${root}server/admin.ts`, "utf8");
    const row = admin.slice(admin.indexOf("JSON.stringify({"), admin.indexOf("}),", admin.indexOf("JSON.stringify({")));
    expect(row).toMatch(/version:/);
  });

  test("the README says what version 0 means, since a bare integer explains nothing", () => {
    const admin = readFileSync(`${root}server/admin.ts`, "utf8");
    expect(admin).toMatch(/MusicBrainz/);
  });

  // ★ THE LABEL IS INCOMPLETE AND THE README USED TO ASSERT IT AS COMPLETE. Adding `version` made
  // the export's claim CHECKABLE, and the first thing a checkable claim did was turn out false:
  // "Everything above `0` is a measurement made from decoded audio." Before c22d16c the /api/features
  // lane called upsertAnalysis({videoId, bpm, key}) with no `version` at all, so those rows took the
  // column default of 1 (migration 0004). They are third-party lookups stamped as ours, they are in
  // production, and no column separates them from a real measurement.
  //
  // So `0` is a reliable POSITIVE signal and `1` is not a guarantee of the opposite — an asymmetry
  // the README has to state, because a consumer filtering `version > 0` would otherwise believe they
  // had removed the lookups. Vagueness overclaimed; the version column made it precise AND wrong,
  // which is worse for exactly the consumer it was added to help.
  test("the README states the asymmetry — `0` positive, `1` not a guarantee", () => {
    const admin = readFileSync(`${root}server/admin.ts`, "utf8");
    const readme = admin.slice(admin.indexOf("const readme ="), admin.indexOf("await hfCommit"));
    // The hole itself: rows that predate the stamp and took the default.
    expect(readme, "the README no longer explains that pre-stamp lookups sit at version 1").toMatch(/default of/);
    expect(readme).toMatch(/not a guarantee/);
  });

  // This one checks for the ABSENCE of a specific sentence rather than of a class, and that limit is
  // the honest description of it: there is no way to grep for "claims the data cannot support". It
  // pins the one universal we know was written, so that re-adding it is a test failure rather than a
  // paragraph nobody re-reads. The positive assertions above are what actually carry the invariant.
  test("the README makes no universal claim about every row above 0", () => {
    const admin = readFileSync(`${root}server/admin.ts`, "utf8");
    const readme = admin.slice(admin.indexOf("const readme ="), admin.indexOf("await hfCommit"));
    expect(readme).not.toMatch(/Everything above/);
  });

  // The body sentence is half of the same claim: "Generated by Handling The Loop" over a table that
  // carries other people's lookups is the assertion `version` exists to qualify, and qualifying the
  // column while leaving the headline unqualified is the half-fix this file already warns about one
  // test up.
  test("the headline does not claim the whole dataset as our own measurement", () => {
    const admin = readFileSync(`${root}server/admin.ts`, "utf8");
    const readme = admin.slice(admin.indexOf("const readme ="), admin.indexOf("await hfCommit"));
    expect(readme).not.toMatch(/no audio\. Generated by/);
  });
});
